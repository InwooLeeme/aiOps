const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const elements=new Map();
const document={querySelectorAll:()=>[],getElementById(id){
  if(!elements.has(id))elements.set(id,{hidden:false,open:true,innerHTML:'',textContent:'',classList:{toggle(){}}});
  return elements.get(id);
}};
const context=vm.createContext({console,Date,Intl,Number,JSON,document});
const source=fs.readFileSync('project/serving_app/static/dashboard.js','utf8');
vm.runInContext(source.slice(0,source.lastIndexOf('init().catch')),context);
const el=id=>document.getElementById(id);
const payload={sequence:Array.from({length:14},(_,i)=>({timestamp:`2024-12-${18+i}T00:00:00`}))};
const result={predicted_generation_mwh:0,target_timestamp:'2025-01-01T00:00:00',region:'제주',model_version:'3',prediction_id:'test',input_end_timestamp:'2024-12-31T00:00:00',issued_at:'2026-10-08T00:00:00+09:00',forecast_context:'historical',monitoring_eligible:false,exclusion_reason:'historical'};
vm.runInContext('refreshDashboard=async()=>{};state.models={versions:[{version:"3",simulation:true},{version:"4",simulation:false}]}',context);
(async()=>{
  el('prediction-input').value=JSON.stringify(payload);
  el('prediction-result-card').innerHTML='old result';
  let resolve;
  context.api=()=>new Promise(r=>{resolve=r;});
  const pending=vm.runInContext('predict()',context);
  assert.equal(el('prediction-result-card').hidden,true,'Hide previous prediction while a new request is pending');
  assert.equal(el('prediction-details').open,false,'Collapse previous JSON at request start');
  resolve(result);await pending;
  assert.equal(el('prediction-result-card').hidden,false);
  let card=el('prediction-result-card').innerHTML;
  for(const label of ['0','MWh','2025-01-01','2024-12-18','2024-12-31','v3','시연 데이터 학습 모델'])assert.ok(card.includes(label),label);
  assert.ok(!card.includes('정확도'));
  context.api=async()=>{throw Object.assign(new Error('잘못된 입력'),{status:422,data:{detail:'잘못된 입력'}});};
  await vm.runInContext('predict()',context);
  assert.equal(el('prediction-result-card').hidden,true,'Do not leave successful result visible after API failure');
  assert.ok(el('prediction-status').innerHTML.includes('잘못된 입력'));
  el('prediction-result-card').hidden=false;
  el('prediction-input').value='{';
  await vm.runInContext('predict()',context);
  assert.equal(el('prediction-result-card').hidden,true,'Malformed JSON must also hide stale results');
  el('prediction-input').value=JSON.stringify(payload);
  context.api=async()=>({...result,model_version:'4',forecast_context:'current',monitoring_eligible:true,exclusion_reason:null});
  await vm.runInContext('predict()',context);
  card=el('prediction-result-card').innerHTML;
  assert.ok(card.includes('v4'));
  assert.ok(!card.includes('시연 데이터 학습 모델'),'Use the returned model version to identify simulation training');
  assert.ok(!card.includes('과거 데이터 점검'));
  console.log('prediction result and stale-state checks passed');
})().catch(error=>{console.error(error);process.exitCode=1;});
